# gen-assets.sh — turn web/xterm/* into webterm_assets.h, the gzipped
# xterm.js and stylesheet that vectis serves for its web terminal
#
# Usage: sh web/gen-assets.sh     (from anywhere; writes webterm_assets.h
#                                  next to vectis.c)
#
# Notes:
#   - Needs gzip and od.  `gzip -9n` (no name, no time stamp) gives the same
#     bytes on every run with GNU gzip, which CI uses to check that the
#     committed header matches web/xterm/.
#   - The served script is xterm.js followed by addon-fit.js.
#

set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
X=$ROOT/web/xterm
OUT=$ROOT/webterm_assets.h

# array NAME: stdin, gzipped, as a C array NAME[] of unsigned char
array() {
	echo "static const unsigned char $1[] = {"
	gzip -9n | od -An -v -tx1 | sed -e 's/  */ /g' -e 's/^ //' -e 's/ $//' \
		-e '/^$/d' -e 's/\([0-9a-f][0-9a-f]\)/0x\1,/g' -e 's/^/    /'
	echo "};"
}

{
	echo "/* Generated by web/gen-assets.sh from web/xterm/ -- do not edit. */"
	echo "/* xterm.js 5.5.0 + addon-fit 0.10.0, MIT: web/xterm/LICENSE */"
	echo
	{ cat "$X/xterm.js"; echo; cat "$X/addon-fit.js"; } | array wt_js_gz
	echo
	array wt_css_gz < "$X/xterm.css"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "gen-assets.sh: $OUT"
